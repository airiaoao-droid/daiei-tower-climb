export interface ModelAssetSpec {
  id: string;
  fileName: string;
  path: string;
  saveFolder: string;
  format: 'GLB (glTF 2.0 Binary)';
  dimensionsMeters: { width: number; height: number; depth: number };
  origin: string;
  animations: string[];
  description: string;
  status: '新規制作（現在はThree.js仮メッシュ）';
}

export interface ImageAssetSpec {
  id: string;
  fileName: string;
  path: string;
  saveFolder: string;
  format: 'PNG' | 'JPG / PNG';
  aspectRatio: string;
  pixelSize: { width: number; height: number };
  transparentRequired: boolean;
  usageLocation: string;
  description: string;
  status: '新規制作（現在はCSS/3Dカラー仮表示）';
}

export interface AudioAssetSpec {
  id: string;
  fileName: string;
  path: string;
  saveFolder: string;
  category: 'bgm' | 'se' | 'ambience';
  format: 'MP3 / WAV';
  durationSeconds: string;
  loop: boolean;
  sampleRateHz: string;
  description: string;
  status: '新規制作（現在はWeb Audio合成音）';
}

